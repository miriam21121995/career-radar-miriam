const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../frontend/index.html'),'utf8');
const from=html.indexOf('function atsBoardFromURL(value)');
const to=html.indexOf('function companyJobSearchUrl(',from);
assert(from>0&&to>from,'V47 official careers candidate mapping is missing');
const ctx={URL,nameKey:s=>String(s||'').trim().toLowerCase()};
vm.createContext(ctx);
vm.runInContext(html.slice(from,to)+';globalThis.testFunctions={atsBoardFromURL,knownOfficialCareersATS,careersATSForCompany}',ctx);
const {atsBoardFromURL,knownOfficialCareersATS,careersATSForCompany}=ctx.testFunctions;
assert.equal(atsBoardFromURL('https://www.optiver.com/join-us/jobs/'),null,'Company website is not a native ATS link');
const candidate=careersATSForCompany('https://www.optiver.com/join-us/jobs/','Optiver');
assert.equal(candidate?.ats,'greenhouse');
assert.equal(candidate?.board,'optiverus');
assert.equal(candidate?.candidate,true);
assert.equal(candidate?.official,'https://www.optiver.com/join-us/jobs/');
assert.equal(knownOfficialCareersATS('https://optiver.com/join-us/jobs/','Other firm'),null);
assert.equal(knownOfficialCareersATS('https://evil-optiver.com/join-us/jobs/','Optiver'),null);
assert.equal(knownOfficialCareersATS('https://optiver.com/not-jobs','Optiver'),null);
assert.equal(knownOfficialCareersATS('http://optiver.com/join-us/jobs/','Optiver'),null);
assert.equal(knownOfficialCareersATS('https://optiver.com:443/join-us/jobs/','Optiver'),null);
assert.equal(careersATSForCompany('https://jobs.lever.co/example','Example').ats,'lever');
console.log('PASS V47: official Careers allowlist, correct ATS mapping and restrictions');
